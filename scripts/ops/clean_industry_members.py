def load():
    return json.load(open(PATH, encoding='utf-8'))


def build_n2c(imap):
    n2c = {}
    for code, r in imap.items():
        nm = r['name'].replace(' ', '')
        keys = {nm}
        for pfx in ('XD', 'XR'):                                    # 除权/除息前缀
            if nm.startswith(pfx) and len(nm) > 3: keys.add(nm[2:])
        for pfx in ('*ST', 'ST'):                                   # ST 变体
            if nm.startswith(pfx) and len(nm) > 4: keys.add(nm[len(pfx):])
        for suf in ('-U', '-UW', '-W', '-J'):                       # 未盈利/加权等后缀
            if nm.endswith(suf): keys.add(nm[:-len(suf)])
        for k in keys:
            n2c.setdefault(k, code)
    return n2c


def resolve(n2c, nm):
    """名称解析：精确 → XD/后缀归一 → 前缀模糊（≥4 字符，避免短名误配）"""
    if nm in n2c: return n2c[nm]
    for k, c in n2c.items():
        if len(nm) >= 3 and len(k) >= 3 and (k.startswith(nm) or nm.startswith(k)):
            return c
    return None


def clean(d, report):
    imap = {r['code']: r for r in d['industryMap']['rows']}
    n2c = build_n2c(imap)
    for ind in d['industries']['list']:
        name = ind['name']
        rule = RULES.get(name)
        if not rule or rule.get('keep_all'):
            if rule and rule.get('keep_all'):
                report.append(f'[保留] {name}: {len(ind["members"])} 家（人工核验过，跳过）')
            continue
        mem = ind.get('members') or []
        sk = set(rule.get('sk') or [])
        wl_codes = set()
        missing_wl = []
        for nm in rule.get('wl') or []:
            c = resolve(n2c, nm)
            if c: wl_codes.add(c)
            else: missing_wl.append(nm)
        drop = set()
        for nm in rule.get('drop') or []:
            c = n2c.get(nm)
            if c: drop.add(c)
        ck = rule.get('ck')
        loose = sk | set(rule.get('loose') or [])
        keep, removed = [], []
        for m in mem:
            r = imap.get(m) or {}
            nm = r.get('name', '').replace(' ', '')
            sw3 = r.get('sw3', '')
            cs = r.get('concepts', '') or ''
            if '退' in nm:
                removed.append((m, nm, '退市')); continue
            if m in drop:
                removed.append((m, nm, '显式剔除')); continue
            if sw3 in sk:
                keep.append(m); continue
            if m in wl_codes:
                keep.append(m); continue
            if ck and any(k in cs for k in ck) and sw3 in loose:
                keep.append(m); continue
            removed.append((m, nm, 'sw3=' + (sw3 or '无') + ' 不在骨架/白名单'))
        ind['members'] = keep
        report.append(f'[清洗] {name}: {len(mem)} → {len(keep)}（移除 {len(removed)}）')
        if missing_wl:
            report.append(f'       ⚠ 白名单未解析: {"、".join(missing_wl)}')
        if removed and len(removed) <= 60:
            for c, nm, why in removed:
                report.append(f'       - {nm}({c}) {why}')
        elif removed:
            bywhy = Counter(w for _, _, w in removed)
            report.append('       移除明细（按原因汇总）: ' + '；'.join(f'{w}×{n}' for w, n in bywhy.most_common()))
    return d


def seed_notes(d, report):
    imap = {r['code']: r for r in d['industryMap']['rows']}
    n2c = build_n2c(imap)
    notes = d['industries'].setdefault('companyNotes', {})
    added, existed, missing = 0, 0, []
    for nm, txt in CNOTES_SEED.items():
        c = resolve(n2c, nm)
        if not c:
            missing.append(nm); continue
        if notes.get(c):
            existed += 1; continue
        notes[c] = txt
        added += 1
    report.append(f'[说明预填] 新增 {added} 条，已存在跳过 {existed} 条' +
                  (f'，未解析: {"、".join(missing)}' if missing else ''))
    return d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--seed-notes', action='store_true')
    args = ap.parse_args()
    if not (args.dry_run or args.apply or args.seed_notes):
        print('用法: --dry-run / --apply / --seed-notes'); return
    d = load()
    report = []
    if args.dry_run or args.apply:
        clean(d, report)
    if args.seed_notes or args.apply:
        seed_notes(d, report)
    print('\n'.join(report))
    if args.apply:
        shutil.copy(PATH, PATH.replace('.json', '.backup-' + datetime.now().strftime('%Y%m%d') + '.json'))
        d.setdefault('meta', {})['updated'] = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.000Z')
        json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
        print('✅ 已写回（原文件备份为 data/invest-data.backup-*.json），meta.updated 已刷新')


if __name__ == '__main__':
    main()
