def main():
    d = json.load(open(PATH, encoding='utf-8'))
    assert 'principles' in d and isinstance(d['principles'].get('principles'), list), 'principles 结构异常'
    bak = PATH.replace('.json', '.backup-20260930-principles.json')
    if not os.path.exists(bak):
        shutil.copy2(PATH, bak)
    ps = d['principles']['principles']
    existing = {p.get('title') for p in ps}
    to_add = [p for p in NEW if p['title'] not in existing]
    skipped = [p['title'] for p in NEW if p['title'] in existing]
    if not to_add:
        print('SKIP: 15 条已全部存在，无新增')
        return
    ps.extend(to_add)
    d['meta']['updated'] = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%f')[:-3] + 'Z'
    json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False)
    # 回读断言
    d2 = json.load(open(PATH, encoding='utf-8'))
    ps2 = d2['principles']['principles']
    titles2 = {p.get('title') for p in ps2}
    ok = all(p['title'] in titles2 for p in to_add)
    assert ok and len(ps2) == len(ps), '回读断言失败'
    cyc = {}
    for p in to_add: cyc[p['cycle']] = cyc.get(p['cycle'], 0) + 1
    print(f"OK: 新增 {len(to_add)} 条 | 跳过 {len(skipped)} 条 | 总数 {len(ps2)} | 周期分布 {cyc} | meta.updated={d2['meta']['updated']}")
    if skipped: print('跳过:', skipped)

if __name__ == '__main__':
    sys.exit(main())
